import unittest
import os
import json
import shutil
from unittest.mock import patch, MagicMock
from datetime import datetime
from core.looper.executors.inbox_executor import InboxExecutor
from adapters.filesystem_adapter import FilesystemAdapter
import app_global_config as config


class TestInboxExecutorWithFilesystemAdapter(unittest.TestCase):
    def setUp(self):
        """Set up test fixtures."""
        # Create a temporary directory for testing
        self.test_dir = os.path.join(os.path.dirname(__file__), 'test_inbox_output')
        os.makedirs(self.test_dir, exist_ok=True)

        # Initialize the executor
        self.executor = InboxExecutor(model="test-model")

        # Mock config for filesystem path
        self.original_fs_path = config.LOOPAI_SINGLE_FILESYSTEM_PATH
        config.LOOPAI_SINGLE_FILESYSTEM_PATH = self.test_dir

        # Set up test data for a POST request with a message
        self.test_post_data = {
            "step_id": "create_tasks",
            "result": [
                {
                    "method": "POST",
                    "path": "/api/public/agent/24/action/RECEIVE_POST/",
                    "url": "http://localhost:5050/api/public/agent/24/action/RECEIVE_POST/",
                    "args": {},
                    "remote_addr": "172.24.0.1",
                    "body": {
                        "message": {
                            "data": "Test message content",
                            "from": "sender/agent",
                            "to": "recipient/agent"
                        }
                    }
                }
            ],
            "session_id": "5e1219cd-ce31-4409-9b48-e4f239876fcc"
        }

        # Initialize the filesystem adapter
        self.adapter = FilesystemAdapter(source="/", global_user_id="1", global_loop_id="180")

    def tearDown(self):
        """Clean up after tests."""
        # Restore original config
        config.LOOPAI_SINGLE_FILESYSTEM_PATH = self.original_fs_path

        # Remove test directory
        if os.path.exists(self.test_dir):
            shutil.rmtree(self.test_dir)

    @patch('datetime.datetime')
    def test_inbox_executor_with_filesystem_adapter(self, mock_datetime):
        """
        Test that InboxExecutor output can be correctly processed by FilesystemAdapter.
        This test verifies the entire flow from executor to file creation.
        """
        # Setup datetime mock for consistent filenames
        mock_now = MagicMock()
        mock_now.strftime.return_value = "20230101_120000"
        mock_datetime.now.return_value = mock_now

        # 1. Run the InboxExecutor
        result = self.executor.run(
            model="test-model",
            system_content="system content",
            user_content=self.test_post_data,
            temperature=0.7
        )

        # 2. Verify result structure is as expected by FilesystemAdapter
        self.assertIn('result', result)
        self.assertIn('updated_files', result['result'])

        # Extract the expected filename from the result for later verification
        expected_files = result['result']['updated_files']
        self.assertGreater(len(expected_files), 0, "No files were generated by the executor")

        expected_filepath = expected_files[0]['path']
        self.assertTrue(expected_filepath.startswith('inbox/'),
                        f"Expected path to start with 'inbox/' but got '{expected_filepath}'")

        # 3. Use the FilesystemAdapter to write the data
        write_success = self.adapter.write("create_tasks", result)

        # 4. Verify the adapter reported success
        self.assertTrue(write_success, "FilesystemAdapter reported failure when writing")

        # 5. Verify the file was actually created
        full_path = os.path.join(self.test_dir, expected_filepath)
        self.assertTrue(os.path.exists(full_path),
                        f"Expected file {full_path} does not exist")

        # 6. Verify the file content is correct
        with open(full_path, 'r') as f:
            file_content = json.load(f)

        self.assertIn('message', file_content)
        self.assertEqual(file_content['message']['data'], 'Test message content')
        self.assertEqual(file_content['message']['from'], 'sender/agent')
        self.assertEqual(file_content['message']['to'], 'recipient/agent')

        # 7. Verify the inbox directory structure is as expected
        inbox_dir = os.path.join(self.test_dir, 'inbox')
        self.assertTrue(os.path.isdir(inbox_dir), "Inbox directory was not created")

        # Verify only one file was created (matching our test case)
        files_in_inbox = os.listdir(inbox_dir)
        self.assertEqual(len(files_in_inbox), 1,
                         f"Expected 1 file in inbox, but found {len(files_in_inbox)}: {files_in_inbox}")


if __name__ == '__main__':
    unittest.main()
